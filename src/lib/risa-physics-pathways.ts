export type PhysicsPathway = (typeof physicsPathways)[number];

export function findPhysicsPathway(code: string): PhysicsPathway | undefined {
  return physicsPathways.find((pathway) => pathway.code.toLowerCase() === code);
}

export function physicsPathwayHref(code: string): string {
  return "/programmes/physics/pathways/" + code.toLowerCase();
}

export function describePhysicsPackage(module: string, code: string): string {
  if (code === "—") return "No default recommendation";
  if (module === "PHY202") {
    return code === "H1"
      ? "Electromagnetic energy conversion"
      : "Mathematical analysis of eddy currents";
  }
  if (module === "PHY203 specialisation" && code === "H1") {
    return "Optical fibres and communications";
  }
  if (module === "PHY304") {
    const mechanics: Record<string, string> = {
      H1: "Theoretical Mechanics",
      H2: "Celestial Mechanics",
      H3: "Engineering Dynamics",
      H4: "Computational Dynamics",
    };
    return mechanics[code] ?? code;
  }
  return code
    .split(",")
    .map((item) => packageNames[item] ?? item)
    .join("; ");
}
